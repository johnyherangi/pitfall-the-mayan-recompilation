#!/usr/bin/env python3
"""Regenerate src/ph/manifests_data.cpp from tools/manifests.json."""
import json, os, sys
root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
m = json.load(open(os.path.join(root, 'tools', 'manifests.json')))
names = ['Ceiba Jungle','Xibalba Falls','Tazamul Mines','Lost City of Copan','Copan Temple','Lakamul Rain Forest',
         'Yaxchilan Lagoon','Balankanche Mine','Tikal Ruins','Temple of Tikal','Warrior Spirit','Loltun Vault 2',
         'Loltun Vault 3','Loltun Vault 1','(continue)','(title)','Palenque Ruins','Tomb of Palenque',
         'Jaina Island Falls','(map)','2600 Level','(intro)','(room)','(credits)','(end)']
out = ['// GENERATED by tools/gen_manifests.py from tools/manifests.json - do not edit by hand.',
       '// Load-order tables recovered from PITFALL.EXE (FUN_004457d0, FUN_00447190, FUN_004460e0, FUN_0043ce10).',
       '#include "ph/manifests.h"\nnamespace ph {',
       'const std::vector<ManifestEntry>& initManifest() {\n  static const std::vector<ManifestEntry> v = {']
out += [f'    {{RecordKind::{"Raw" if k == "raw" else "Sprite"}, "{n}"}},' for k, n in m['init']]
out += ['  };\n  return v;\n}', 'const std::vector<LevelFiles>& levelFiles() {\n  static const std::vector<LevelFiles> v = {']
for lv in range(25):
    f = m['level_files'][str(lv)]
    vals = [f[0][1], f[1][1], f[2][1], f[3][1], f[4][1], f[5][1], f[6][1] if len(f) > 6 else '']
    out.append('    {' + ', '.join(f'"{v}"' for v in vals) + '},')
out += ['  };\n  return v;\n}', 'const std::vector<std::string>& levelSprites(int level) {\n  static const std::vector<std::vector<std::string>> v = {']
for lv in range(25):
    out.append('    {' + ', '.join(f'"{n}"' for _, n in m['levels'].get(str(lv), [])) + '},')
out += ['  };\n  static const std::vector<std::string> empty;\n  return (level >= 0 && level < (int)v.size()) ? v[level] : empty;\n}',
        'const std::vector<SoundEntry>& soundManifest() {\n  static const std::vector<SoundEntry> v = {']
out += [f'    {{"{n}", {i}}},' for n, i in m['sounds']]
out += ['  };\n  return v;\n}',
        'const char* levelName(int level) {\n  static const char* const n[] = {' + ', '.join(f'"{x}"' for x in names) + '};\n  return (level >= 0 && level < 25) ? n[level] : "?";\n}',
        '} // namespace ph']
open(os.path.join(root, 'src', 'ph', 'manifests_data.cpp'), 'w').write('\n'.join(out) + '\n')
print('wrote src/ph/manifests_data.cpp')
