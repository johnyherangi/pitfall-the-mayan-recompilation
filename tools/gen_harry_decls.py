#!/usr/bin/env python3
"""Generate the declarations of Harry's state functions for PlayLogic (src/game/harry_decls.inc).

The state code in src/game/harry_*.cpp defines one PlayLogic member per original address
(hXXXXXX).  This script collects their signatures into harry_decls.inc, which play_logic.h
includes inside the class.  Functions that are called but not ported yet get a declaration
and a stub in src/game/harry_stubs.cpp (a state stub reports itself and falls back to the
standing state), so the port builds at every step.
"""
import os, re, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
src = os.path.join(root, 'src', 'game')
files = [f for f in sorted(os.listdir(src)) if (f.startswith('harry') or f == 'play_logic.cpp') and f.endswith('.cpp') and f != 'harry_stubs.cpp']
defs = {}
calls = set()
conts = set()
# continuation addresses the object handlers write into DAT_00465b69 (outside the state code)
EXTERNAL_CONTS = [0x426fee, 0x42709d, 0x427316, 0x42756d, 0x428780, 0x428e50, 0x42939b, 0x429fe2, 0x42a048,
                  0x42a6e7, 0x42aa3b, 0x42abaa, 0x42c244, 0x42c2cc, 0x42c2ff, 0x42c3bc, 0x42c518, 0x42cdb6,
                  0x42d2ca, 0x42e297, 0x42ea8b, 0x42f574, 0x42f88c]
conts.update(EXTERNAL_CONTS)
for f in sorted(os.listdir(src)):
    if f.endswith('.cpp'):
        for m in re.finditer(r'setCont\((0x[0-9a-f]{6})\)', open(os.path.join(src, f)).read()):
            conts.add(int(m.group(1), 16))
for f in files:
    s = open(os.path.join(src, f)).read()
    for m in re.finditer(r'^(\w[\w\s\*&:<>]*?)\s+PlayLogic::(h[0-9a-f]{6})\(([^)]*)\)\s*(?:const\s*)?\{', s, re.M):
        defs[m.group(2)] = (m.group(1).strip(), m.group(3).strip())
    for m in re.finditer(r'\b(h[0-9a-f]{6})\(', s):
        calls.add(m.group(1))
missing = sorted(calls - set(defs))
out = ['// GENERATED by tools/gen_harry_decls.py - do not edit.',
       '// Harry\'s state code: one member per original address (src/game/harry_states.cpp).']
for name in sorted(defs):
    ret, args = defs[name]
    out.append(f'{ret} {name}({args});')
if missing:
    out.append('// not ported yet (stubs in harry_stubs.cpp)')
    for name in missing:
        out.append(f'void {name}();')
open(os.path.join(src, 'harry_decls.inc'), 'w', newline='\n').write('\n'.join(out) + '\n')
disp = ['// GENERATED by tools/gen_harry_decls.py - do not edit.',
        '// The continuations of DAT_00465b69 (the `call eax` of FUN_00426810).']
nodisp = []
for a in sorted(conts):
    name = f'h{a:06x}'
    if name in defs and defs[name] == ('void', ''):
        disp.append(f'case {a:#x}: {name}(); return;')
    else:
        nodisp.append(name)
open(os.path.join(src, 'harry_dispatch.inc'), 'w', newline='\n').write('\n'.join(disp) + '\n')
if nodisp: print('continuations without a state function:', ' '.join(nodisp))
stub = ['// GENERATED by tools/gen_harry_decls.py - do not edit.',
        '// Placeholders for the parts of Harry\'s state code that are not ported yet.',
        '#include "game/play_logic.h"', '', 'namespace game {', '']
for name in missing:
    stub.append(f'void PlayLogic::{name}() {{ notPorted(0x{name[1:]}); }}')
stub += ['', '} // namespace game']
open(os.path.join(src, 'harry_stubs.cpp'), 'w', newline='\n').write('\n'.join(stub) + '\n')
print(f'{len(defs)} ported, {len(missing)} stubs: {" ".join(missing)}')
