#!/usr/bin/env python3
"""Regenerate src/ph/arena_data.cpp from original/PITFALL.EXE.

The original loads INIT.PH and each level into one 1.5 MB block (ph::Arena), a record after the
other.  A sprite record keeps its bytes there with two header fields replaced by FUN_004453a0:
+4 (the palette's offset) by the pointer to its name and +8 (its colour count) by
FUN_004361ee's result for its slot, the word 4 + 12 * k of the slot's entry k in the box table
at 0x468824 (0xffff without one).  This tool reads, in load order, the name pointer and the slot
of every sprite FUN_004457d0 (INIT.PH) and FUN_00447190 (each level, by its jump table at
0x4496e0) load: the `push slot; push name; call 0x4453a0` sequences of their code.
"""
import os, struct, sys

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
exe = sys.argv[1] if len(sys.argv) > 1 else os.path.join(root, 'original', 'PITFALL.EXE')
d = open(exe, 'rb').read()
pe = struct.unpack_from('<I', d, 0x3c)[0]
nsec = struct.unpack_from('<H', d, pe + 6)[0]; opt = struct.unpack_from('<H', d, pe + 20)[0]
secs = []
for i in range(nsec):
    o = pe + 24 + opt + i * 40
    vs, va, rs, ro = struct.unpack_from('<IIII', d, o + 8); secs.append((va, ro, max(rs, vs)))


def rd(va, n):
    for sva, ro, rs in secs:
        if sva <= va - 0x400000 < sva + rs:
            o = ro + (va - 0x400000 - sva); return d[o:o + n]
    raise ValueError(hex(va))


def cstr(va):
    b = rd(va, 64)
    return b[:b.index(0)].decode('latin-1')


def calls(start, end):
    """The (name, slot) of each `push slot; push name; call 0x4453a0` in [start, end)."""
    code = rd(start, end - start); out = []
    for i in range(len(code) - 15):
        if code[i] == 0x68 and code[i + 5] == 0x68 and code[i + 10] == 0xe8:
            target = start + i + 15 + struct.unpack_from('<i', code, i + 11)[0]
            if target == 0x4453a0:
                out.append((struct.unpack_from('<I', code, i + 6)[0], struct.unpack_from('<I', code, i + 1)[0]))
    return out


def case_calls(va):
    """A case of FUN_00447190: its calls up to its `ret`."""
    code = rd(va, 0x4000); out = []; i = 0
    while code[i] != 0xc3:
        if code[i] == 0x68 and code[i + 5] == 0x68 and code[i + 10] == 0xe8 and code[i + 15:i + 18] == b'\x83\xc4\x08':
            out.append((struct.unpack_from('<I', code, i + 6)[0], struct.unpack_from('<I', code, i + 1)[0]))
            i += 18
        else:
            raise ValueError(f'unexpected byte {code[i]:#x} at {va + i:#x}')
    return out


boxes = []
va = 0x468824
while struct.unpack_from('<I', rd(va, 4))[0] != 0xffffffff:
    boxes.append(struct.unpack_from('<I', rd(va, 4))[0]); va += 12


def box_word(slot):
    return (4 + 12 * boxes.index(slot)) & 0xffff if slot in boxes else 0xffff


init = calls(0x4457d0, 0x4460e0)
table = [struct.unpack_from('<I', rd(0x4496e0 + 4 * lv, 4))[0] for lv in range(25)]
levels = []
seen = {}
for lv, va in enumerate(table):
    if va in seen: levels.append(levels[seen[va]]); continue
    seen[va] = lv
    levels.append(case_calls(va))

out = ['// GENERATED by tools/gen_arena_data.py from PITFALL.EXE - do not edit by hand.',
       '// The sprite records as FUN_004453a0 leaves them in the load block: their name pointers (+4) and',
       '// box words (+8, FUN_004361ee), in the load order of FUN_004457d0 (INIT.PH) and FUN_00447190, with',
       '// the sprite slot each call fills.',
       '#include "ph/arena.h"', '', 'namespace ph {', '',
       'namespace {']
def emit(name, lst):
    out.append(f'const ArenaSprite {name}[] = {{')
    for n, s in lst:
        out.append(f'    {{0x{n:06x}, 0x{box_word(s):04x}, "{cstr(n)}", 0x{s:06x}}},')
    out.append('};')
emit('kInit', init)
for lv in range(25):
    if seen.get(table[lv]) == lv and levels[lv]: emit(f'kLevel{lv}', levels[lv])
out.append('} // namespace')
out.append('')
out.append('std::span<const ArenaSprite> initArenaSprites() { return kInit; }')
out.append('')
out.append('std::span<const ArenaSprite> levelArenaSprites(int level) {')
out.append('    switch (level) {')
for lv in range(25):
    src = seen[table[lv]]
    if levels[lv]: out.append(f'    case {lv}: return kLevel{src};')
out.append('    default: return {};')
out.append('    }')
out.append('}')
out.append('')
out.append('} // namespace ph')
open(os.path.join(root, 'src', 'ph', 'arena_data.cpp'), 'w').write('\n'.join(out) + '\n')
print('wrote src/ph/arena_data.cpp:', len(init), 'INIT sprites,', sum(len(l) for l in levels), 'level sprites')
